// Isolated real-browser UI contract tests; no notification service is contacted.
// Run: node e2e/oncall-ui.mjs
import { chromium } from 'playwright';
import { createServer } from 'node:http';
import { readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';
const root = fileURLToPath(new URL('../', import.meta.url));
const now = new Date('2026-10-30T03:00:00Z');
const rot = { name: 'primary', rotate: 'daily', handoff: '09:00', tz: 'America/New_York', now: 'alice', scheduled: { member: 'alice', from: '2026-10-30T00:00:00Z', until: '2026-10-31T00:00:00Z' }, members: [{channel:'alice',people:['Alice Long Responder Name']},{channel:'bob',people:['Bob']}], policies:['default'], overrides:[], shifts:[{member:'alice',from:'2026-10-30T00:00:00Z',until:'2026-10-31T00:00:00Z'},{member:'bob',from:'2026-10-31T00:00:00Z',until:'2026-11-01T00:00:00Z'}] };
const writes = [];
let failWrite = false;
let failOverview = false;
let failChannels = false;
const server = createServer(async (req,res) => {
  const path = new URL(req.url, 'http://localhost').pathname;
  const json = data => { res.setHeader('Content-Type','application/json'); res.end(JSON.stringify(data)); };
  if (req.method === 'POST') {
    let body=''; for await (const chunk of req) body += chunk;
    writes.push({path, body:JSON.parse(body)});
    await new Promise(r=>setTimeout(r,350));
    if (failWrite) { res.statusCode=400; return json({message:'Request rejected'}); }
    return json({});
  }
  if ((failOverview && path === '/api/v1/oncall') || (failChannels && path === '/api/v1/channels')) { res.statusCode=503; return json({message:'Read temporarily unavailable'}); }
  if (path === '/api/v1/oncall') return json({rotations:[rot],stats:{from:now.toISOString(),to:now.toISOString(),all:{incidents:0,acked:0,resolved:0},members:[]}});
  if (path === '/api/v1/channels') return json([{name:'alice',kind:'log'}, {name:'bob',kind:'log'}]);
  if (path === '/api/v1/oncall/calendar') return json({rotations:[{name:rot.name,segments:rot.shifts}]});
  if (path === '/api/v1/i18n/en') {
    const cat=JSON.parse(await readFile(root+'internal/i18n/locales/en.json','utf8'));
    return json(cat);
  }
  if (path.startsWith('/api/')) return json({});
  if (path === '/') { res.setHeader('Content-Type','text/html'); return res.end('<link rel="stylesheet" href="/app.css"><link rel="stylesheet" href="/oncall.css"><div id="app"></div><script type="module">import {html,render} from "/js/lib.js"; import {setLang} from "/js/i18n.js"; import {OnCall} from "/js/views/oncall.js"; await setLang("en"); render(html`<${OnCall} />`,document.getElementById("app"));</script>'); }
  try {res.setHeader('Content-Type',path.endsWith('.js')?'text/javascript':'text/css');res.end(await readFile(root+'web/ui'+path));} catch {res.statusCode=404;res.end();}
});
await new Promise(r=>server.listen(0,'127.0.0.1',r));
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({timezoneId:'Asia/Tokyo',viewport:{width:1100,height:900}});
const errors=[]; page.on('pageerror',e=>errors.push(e.message));
await page.clock.install({time:now});
try {
  await page.goto(`http://127.0.0.1:${server.address().port}`);
  await page.locator('.oc-rot').waitFor();
  await page.locator('.oc-rot .hd button').first().click();
  const inputs=page.locator('.modal input[type=datetime-local]');
  await inputs.nth(0).fill('2026-10-30T14:00');
  await inputs.nth(1).fill('2026-10-30T13:00');
  await page.locator('.modal form').evaluate(f=>f.dispatchEvent(new Event('submit',{bubbles:true,cancelable:true})));
  await page.waitForTimeout(100);
  assert.equal(writes.length,0,'reversed date range must never reach API');
  assert.match(await page.locator('.modal').innerText(),/end.*after.*start/i);
  console.log('PASS stand-in rejects reversed dates before API');
  await inputs.nth(1).fill('2026-10-30T15:00');
  failWrite=true;
  await page.locator('.modal form').evaluate(f=>{ for(let i=0;i<3;i++) f.dispatchEvent(new Event('submit',{bubbles:true,cancelable:true})); });
  await page.waitForTimeout(100);
  assert.equal(writes.length,1,'rapid stand-in submits must send exactly one write');
  assert.equal(await page.locator('.modal .btn.primary').isDisabled(),true);
  await page.waitForTimeout(450);
  assert.equal(await page.locator('.modal .btn.primary').isDisabled(),false,'server error permits retry');
  assert.deepEqual(writes[0].body,{rotation:'primary',member:'bob',from:'2026-10-30T05:00:00.000Z',until:'2026-10-30T06:00:00.000Z',note:''});
  console.log('PASS stand-in pending guard, retry, local-to-UTC API contract');
  assert.match(await page.locator('.modal').innerText(),/Asia\/Tokyo/,'entry timezone must be explicit');
  await page.locator('.modal button[type=button]').last().click();
  await page.locator('.oc-rot .hd button').nth(1).click();
  assert.match(await page.locator('.modal').innerText(),/Asia\/Tokyo/,'swap display timezone must be explicit');
  await page.locator('.modal form').evaluate(f=>{for(let i=0;i<3;i++) f.dispatchEvent(new Event('submit',{bubbles:true,cancelable:true}));});
  await page.waitForTimeout(100);
  assert.equal(writes.length,2,'rapid swaps must send one request');
  assert.equal(await page.locator('.modal .btn.primary').isDisabled(),true);
  await page.waitForTimeout(450);
  assert.deepEqual(writes[1].body,{rotation:'primary',a:rot.shifts[0].from,b:rot.shifts[1].from,note:''});
  await page.locator('.modal select').nth(1).selectOption('0');
  await page.locator('.modal form').evaluate(f=>f.dispatchEvent(new Event('submit',{bubbles:true,cancelable:true})));
  await page.waitForTimeout(100);
  assert.equal(writes.length,2,'same-member swap must be blocked even on form submit');
  console.log('PASS explicit timezone, swap guard and unchanged API timestamps');
  await page.locator('.modal button[type=button]').last().click();
  assert.match(await page.locator('.oc-rot').innerText(),/Next scheduled handoff/);
  assert.match(await page.locator('.oc-handoff').innerText(),/Oct 31.*09:00/);
  const day = page.locator('.oc-day').filter({has:page.locator('.oc-date', {hasText:/^(31|.*Oct 31.*)$/})});
  assert.equal(await day.locator('.oc-seg').count(),2,'month must retain morning coverage before handoff');
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.locator('.oc-cal').evaluate(e=>getComputedStyle(e).gridTemplateColumns.split(' ').length),1,'mobile uses a readable daily list');
  assert.match(await day.locator('.oc-date').innerText(),/Sat.*Oct 31|Oct 31.*Sat/);
  assert.equal(await day.locator('.oc-time').last().isVisible(),true,'mobile handoff times stay visible');
  assert.match(await day.locator('.oc-seg').first().innerText(),/12:00 AM–09:00 AM/,'carried-over shift shows its visible daily interval');
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth),true,'no horizontal page overflow');
  assert.deepEqual(errors,[]);
  console.log('PASS scheduled handoff, complete calendar coverage and mobile daily list');
  // Server-provided current responder and base schedule are distinct facts.
  rot.now='bob';
  rot.stand_in={member:'bob',from:rot.shifts[0].from,until:'2026-11-02T00:00:00Z'};
  await page.reload();
  await page.locator('.oc-handoff').waitFor();
  assert.equal(await page.locator('.oc-now b').innerText(),'Bob');
  assert.equal(await page.locator('.oc-handoff time').getAttribute('datetime'),rot.scheduled.until);
  await page.locator('.oc-rot .hd button').first().click();
  await page.locator('.modal input[type=datetime-local]').nth(0).fill('');
  await page.locator('.modal form').evaluate(f=>f.dispatchEvent(new Event('submit',{bubbles:true,cancelable:true})));
  await page.waitForTimeout(100);
  assert.equal(writes.length,2,'missing date must not reach the API');
  await page.locator('.modal input[type=datetime-local]').nth(0).fill('2026-10-30T15:00');
  await page.locator('.modal input[type=datetime-local]').nth(1).fill('2026-10-30T15:00');
  await page.locator('.modal form').evaluate(f=>f.dispatchEvent(new Event('submit',{bubbles:true,cancelable:true})));
  await page.waitForTimeout(100);
  assert.equal(writes.length,2,'zero-duration override must not reach the API');
  await page.locator('.modal input[type=datetime-local]').nth(1).fill('2026-10-30T16:00');
  failWrite=false;
  await page.locator('.modal .btn.primary').click();
  await page.locator('.modal').waitFor({state:'detached'});
  assert.equal(writes.length,3);
  assert.deepEqual(errors,[]);
  console.log('PASS override does not relabel scheduled boundary; invalid dates and successful save');
  await page.reload();
  await page.locator('.oc-cal').waitFor();
  assert.equal(await page.locator('.oc-day').count(), 7, 'fresh mobile view defaults to one week, not a six-week wall');
  await page.getByRole('button', { name: 'Month', exact: true }).click();
  assert.equal(await page.locator('.oc-day').count(), 42, 'mobile users can still choose the full month');
  await page.reload();
  await page.locator('.oc-cal').waitFor();
  assert.equal(await page.locator('.oc-day').count(), 42, 'explicit month choice persists on mobile');
  await page.evaluate(() => localStorage.removeItem('unagikuma.ocview'));
  await page.setViewportSize({width:1100,height:900});
  await page.reload();
  await page.locator('.oc-cal').waitFor();
  assert.equal(await page.locator('.oc-day').count(), 42, 'desktop keeps the month default');
  console.log('PASS mobile week default and explicit month selection');
  await page.getByRole('button', {name:'New rotation',exact:true}).click();
  const beforeCreate = writes.length;
  await page.locator('.modal form').evaluate(f=>f.dispatchEvent(new Event('submit',{bubbles:true,cancelable:true})));
  await page.waitForTimeout(100);
  assert.equal(writes.length,beforeCreate,'empty-member rotation must be rejected even on form submit');
  await page.locator('.modal label.switch input').nth(0).check();
  await page.locator('.modal label.switch input').nth(1).check();
  failWrite=true;
  await page.locator('.modal form').evaluate(f=>{for(let i=0;i<3;i++)f.dispatchEvent(new Event('submit',{bubbles:true,cancelable:true}));});
  await page.waitForTimeout(100);
  assert.equal(writes.length,beforeCreate+1,'rotation creation submits once');
  assert.equal(await page.locator('.modal .btn.primary').isDisabled(),true);
  await page.waitForTimeout(450);
  assert.equal(await page.locator('.modal .btn.primary').isDisabled(),false);
  failWrite=false;
  failOverview=true;
  await page.locator('.modal .btn.primary').click();
  await page.locator('.modal').waitFor({state:'detached'});
  assert.equal(writes.length,beforeCreate+2);
  assert.equal(writes.at(-1).body.opts.members,'alice,bob');
  assert.deepEqual(errors,[]);
  console.log('PASS rotation creation validates members, prevents duplicates and permits retry');
  await page.waitForTimeout(100);
  assert.equal(await page.locator('.page > .banner.error').count(),1,'background refresh errors must not silently leave stale on-call data');
  failOverview=false;
  await page.locator('.page > .banner.error button').click();
  await page.locator('.page > .banner.error').waitFor({state:'detached'});
  failChannels=true;
  await page.reload();
  await page.locator('.oc-rot').waitFor();
  assert.equal(await page.locator('.page > .banner.error').count(),1,'channel-fetch failure must explain disabled creation');
  failChannels=false;
  await page.locator('.page > .banner.error button').click();
  await page.locator('.page > .banner.error').waitFor({state:'detached'});
  assert.equal(await page.getByRole('button',{name:'New rotation',exact:true}).isEnabled(),true);
  console.log('PASS visible stale-data and channel-fetch errors with retry');
} finally { await browser.close(); await new Promise(r=>server.close(r)); }
